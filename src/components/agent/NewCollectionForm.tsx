'use client';

import { useMemo, useState, useTransition } from 'react';
import { useRouter } from 'next/navigation';
import { openFieldSession, type FieldActionState } from '@/lib/operations/field-actions';
import { HatsiSpinner } from '@/components/loading/HatsiActionLoader';

interface MarketOption {
  id: number;
  name: string;
  stateName: string | null;
  assignmentStatus: string | null;
  commodityCount: number;
}

interface TaskOption {
  id: number;
  marketId: number;
  marketName: string;
  dueOn: string;
  commodityNames: string[];
  expectedCount: number;
}

/**
 * Open a collection session.
 *
 * The market is chosen first, because everything that follows is recorded
 * against it. A task may be attached to link the visit to the plan; the
 * session reference is generated by the database, not here.
 */
export function NewCollectionForm({
  markets,
  tasks,
  preselectedMarketId,
  preselectedTaskId,
}: {
  markets: MarketOption[];
  tasks: TaskOption[];
  preselectedMarketId: number | null;
  preselectedTaskId: number | null;
}) {
  const router = useRouter();
  const [state, setState] = useState<FieldActionState>({ ok: false, message: '' });
  const [pending, startTransition] = useTransition();

  const [marketId, setMarketId] = useState(preselectedMarketId ? String(preselectedMarketId) : '');
  const [taskId, setTaskId] = useState(preselectedTaskId ? String(preselectedTaskId) : '');
  const [notes, setNotes] = useState('');
  const [location, setLocation] = useState<{ lat: number; lon: number } | null>(null);
  const [locationError, setLocationError] = useState('');

  const marketTasks = useMemo(
    () => tasks.filter((task) => String(task.marketId) === marketId),
    [tasks, marketId],
  );

  const selectedMarket = markets.find((market) => String(market.id) === marketId);

  /**
   * Confirm the position. This is optional: the agent may be asked for it,
   * but the app never refuses a collection because the phone could not get a
   * fix. The coordinate is recorded for the visit, never as the price.
   */
  const onConfirmLocation = () => {
    setLocationError('');
    if (typeof navigator === 'undefined' || !navigator.geolocation) {
      setLocationError('This device cannot report a position. Carry on without it.');
      return;
    }
    navigator.geolocation.getCurrentPosition(
      (position) => {
        setLocation({
          lat: Number(position.coords.latitude.toFixed(6)),
          lon: Number(position.coords.longitude.toFixed(6)),
        });
      },
      (error) => {
        setLocationError(
          error.code === error.PERMISSION_DENIED
            ? 'Position access was declined. Carry on without it.'
            : 'A position could not be read just now. Carry on without it.',
        );
      },
      { enableHighAccuracy: true, timeout: 8000, maximumAge: 60_000 },
    );
  };

  const onSubmit = () => {
    startTransition(async () => {
      const formData = new FormData();
      formData.set('marketId', marketId);
      formData.set('taskId', taskId);
      formData.set('notes', notes);

      // The coordinate is only sent when the agent actually confirmed one.
      // Sending an empty string would be a claim that a position exists.
      if (location) {
        formData.set('latitude', String(location.lat));
        formData.set('longitude', String(location.lon));
      }

      const result = await openFieldSession({ ok: false, message: '' }, formData);
      setState(result);
      if (result.ok && result.observationId) {
        router.push(`/agent/collection/${result.observationId}`);
      }
    });
  };

  return (
    <div className="space-y-5">
      {/* --------------------------------------------------------- the market */}
      <section className="rounded-xl border border-ink-200 bg-white p-4">
        <h2 className="text-base font-bold text-ink-900">Which market are you at?</h2>
        <p className="mt-1 text-xs leading-relaxed text-ink-500">
          Only the markets in your coverage are listed.
        </p>

        <div className="mt-3 space-y-2">
          {markets.map((market) => {
            const selected = String(market.id) === marketId;
            const paused = market.assignmentStatus === 'paused';
            return (
              <button
                key={market.id}
                type="button"
                disabled={paused}
                onClick={() => {
                  setMarketId(String(market.id));
                  setTaskId('');
                }}
                aria-pressed={selected}
                className={`flex min-h-[56px] w-full items-center justify-between gap-3 rounded-xl border px-3 py-2 text-left ${
                  selected
                    ? 'border-brand-600 bg-brand-50'
                    : 'border-ink-200 bg-white'
                } ${paused ? 'opacity-60' : ''}`}
              >
                <span className="min-w-0">
                  <span className="block truncate text-sm font-bold text-ink-900">
                    {market.name}
                  </span>
                  <span className="block text-[11px] text-ink-500">
                    {market.stateName ?? 'Unknown state'} · {market.commodityCount} commodity(s)
                    {paused ? ' · assignment paused' : ''}
                  </span>
                </span>
                <span
                  className={`size-5 shrink-0 rounded-full border-2 ${
                    selected ? 'border-brand-600 bg-brand-600' : 'border-ink-300'
                  }`}
                  aria-hidden="true"
                />
              </button>
            );
          })}
        </div>
      </section>

      {/* ------------------------------------------------------------ the task */}
      {marketId ? (
        <section className="rounded-xl border border-ink-200 bg-white p-4">
          <h2 className="text-base font-bold text-ink-900">Is this for an assignment?</h2>
          <p className="mt-1 text-xs leading-relaxed text-ink-500">
            Attaching the task links this visit to the plan. You can also collect without one.
          </p>

          <div className="mt-3 space-y-2">
            <label className="flex min-h-[48px] items-center gap-3 rounded-xl border border-ink-200 bg-white px-3 py-2">
              <input
                type="radio"
                name="task"
                value=""
                checked={taskId === ''}
                onChange={() => setTaskId('')}
                className="size-5 accent-brand-700"
              />
              <span className="text-sm font-semibold text-ink-800">
                No assignment — an extra visit
              </span>
            </label>

            {marketTasks.map((task) => (
              <label
                key={task.id}
                className="flex min-h-[48px] items-center gap-3 rounded-xl border border-ink-200 bg-white px-3 py-2"
              >
                <input
                  type="radio"
                  name="task"
                  value={task.id}
                  checked={taskId === String(task.id)}
                  onChange={() => setTaskId(String(task.id))}
                  className="size-5 accent-brand-700"
                />
                <span className="min-w-0">
                  <span className="block truncate text-sm font-semibold text-ink-800">
                    {task.commodityNames.length > 0
                      ? task.commodityNames.join(', ')
                      : 'Market round'}
                  </span>
                  <span className="block text-[11px] text-ink-500">
                    Due {task.dueOn}
                    {task.expectedCount > 0 ? ` · ${task.expectedCount} expected` : ''}
                  </span>
                </span>
              </label>
            ))}
          </div>
        </section>
      ) : null}

      {/* -------------------------------------------------------- the position */}
      <section className="rounded-xl border border-ink-200 bg-white p-4">
        <h2 className="text-base font-bold text-ink-900">Confirm your position (optional)</h2>
        <p className="mt-1 text-xs leading-relaxed text-ink-500">
          If the market has more than one entrance, a position helps the office understand where
          the price was taken. It is never required, and it never becomes part of the price.
        </p>

        <button
          type="button"
          onClick={onConfirmLocation}
          className="mt-3 inline-flex min-h-[44px] w-full items-center justify-center rounded-xl border border-ink-200 bg-white px-4 py-2 text-sm font-bold text-ink-800"
        >
          {location ? 'Position confirmed — check again' : 'Use my current position'}
        </button>

        {location ? (
          <p className="mt-2 text-xs font-semibold tabular-nums text-brand-700">
            Recorded position: {location.lat}, {location.lon}
          </p>
        ) : null}
        {locationError ? (
          <p className="mt-2 text-xs font-semibold text-warning-700">{locationError}</p>
        ) : null}
      </section>

      {/* ------------------------------------------------------------- the notes */}
      <section className="rounded-xl border border-ink-200 bg-white p-4">
        <label className="block">
          <span className="text-base font-bold text-ink-900">
            Note about this visit (optional)
          </span>
          <textarea
            value={notes}
            onChange={(event) => setNotes(event.target.value)}
            rows={2}
            placeholder="Anything unusual about the market today."
            className="mt-2 w-full rounded-xl border border-ink-200 bg-white px-3 py-2 text-sm text-ink-900 placeholder:text-ink-400 focus:border-brand-500 focus:outline-none"
          />
        </label>
      </section>

      {state.message ? (
        <p
          role="status"
          className={`rounded-xl border p-3 text-sm font-semibold ${
            state.ok ? 'border-brand-200 bg-brand-50 text-brand-800' : 'border-error-200 bg-error-50 text-error-700'
          }`}
        >
          {state.message}
        </p>
      ) : null}

      <button
        type="button"
        onClick={onSubmit}
        disabled={pending || !marketId}
        aria-busy={pending}
        className="inline-flex min-h-[52px] w-full items-center justify-center gap-2 rounded-xl bg-brand-700 px-4 py-3 text-base font-bold text-white disabled:opacity-60"
      >
        {pending ? (
          <>
            <HatsiSpinner />
            Opening…
          </>
        ) : (
          `Open the session${selectedMarket ? ` at ${selectedMarket.name}` : ''}`
        )}
      </button>
    </div>
  );
}
